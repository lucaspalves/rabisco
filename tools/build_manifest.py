"""Write koreader/manifest.txt: the file list the Rabisco installer downloads.

Run this before every push that changes anything under koreader/.

Usage: python3 tools/build_manifest.py [version]
       (version defaults to today's date plus a counter, e.g. 2026.11.08-2)
"""
import datetime
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "koreader")
OUT = os.path.join(ROOT, "manifest.txt")
SKIP = {"manifest.txt"}


def next_version():
    today = datetime.date.today().strftime("%Y.%m.%d")
    try:
        old = re.search(r"^version (\S+)", open(OUT).read(), re.M).group(1)
    except (OSError, AttributeError):
        old = ""
    if old.startswith(today):
        n = int(old.split("-")[1]) + 1 if "-" in old else 2
        return "%s-%d" % (today, n)
    return today


def main():
    version = sys.argv[1] if len(sys.argv) > 1 else next_version()
    files = []
    for base, dirs, names in os.walk(ROOT):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        for name in sorted(names):
            rel = os.path.relpath(os.path.join(base, name), ROOT).replace(os.sep, "/")
            if name.startswith(".") or rel in SKIP or " " in rel:
                continue
            files.append((os.path.getsize(os.path.join(base, name)), rel))
    with open(OUT, "w") as f:
        f.write("# Rabisco installer manifest. Generated by tools/build_manifest.py: don't edit by hand.\n")
        f.write("version %s\n" % version)
        for size, rel in files:
            f.write("file %d %s\n" % (size, rel))
    print("manifest %s: %d files, %.1f MB" % (version, len(files), sum(s for s, _ in files) / 1048576))


if __name__ == "__main__":
    main()
